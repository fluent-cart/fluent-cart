    /**
     * Spec: Cases/Functional/subscriptions.md [29]
     *   "Generating an early-payment link for a canceled or expired subscription is
     *    rejected with a clear error."
     */
    public function generatingEarlyPaymentLinkForCanceledOrExpiredSubscriptionIsRejected(FunctionalTester $I): void
    {

        $I->loginAsSuperAdmin();

        // The status guard at line 182 rejects any status NOT in {ACTIVE, TRIALING}; the spec
        // explicitly names canceled and expired. Probe both to honor the "canceled OR expired"
        // clause; otherwise a regression where one branch is whitelisted but the other isn't
        // would slip through.
        $cases = [
            ['status' => Status::SUBSCRIPTION_CANCELED, 'label' => 'canceled'],
            ['status' => Status::SUBSCRIPTION_EXPIRED,  'label' => 'expired'],
        ];

        foreach ($cases as $case) {
            [, , $order, $subscription] = $this->buildSubscriptionChain([
                'item_name'  => 'EarlyPay Probe 29 ' . $case['label'],
                'status'     => $case['status'],
                'bill_times' => 12,
                'bill_count' => 3,
            ], ['email' => 'early-pay-29-' . $case['label'] . '@example.test']);

            [$status, $body] = $I->post(
                '/fluent-cart/v2/orders/' . (int) $order->id . '/subscriptions/' . (int) $subscription->id . '/early-payment-link',
                []
            );

            Assert::assertSame(
                422,
                $status,
                $case['label'] . ' subscription must be rejected with sendError 422. Body: ' . wp_json_encode($body)
            );
            Assert::assertStringContainsString(
                'Subscription must be active',
                (string) ($body['message'] ?? ''),
                $case['label'] . '-status rejection message must name the active-status requirement per app/Modules/Subscriptions/Http/Controllers/SubscriptionController.php:184'
            );
            Assert::assertArrayNotHasKey(
                'payment_url',
                (array) $body,
                $case['label'] . ' rejection must NOT leak a payment_url'
            );
        }
    }

