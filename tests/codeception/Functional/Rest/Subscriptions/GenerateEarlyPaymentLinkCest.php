use Tests\Support\Factory\OrderFactory;
use Tests\Support\FunctionalTester;
use Tests\Support\Traits\BuildsSubscriptions;

/**
 * Spec: Cases/Functional/subscriptions.md → "Generating an early-payment link" section,
 *       items 25-30.
 *
 * Route: POST /fluent-cart/v2/orders/{order}/subscriptions/{subscription}/early-payment-link
 * Controller: SubscriptionController::generateEarlyPaymentLink
 *   (app/Modules/Subscriptions/Http/Controllers/SubscriptionController.php:372-426)
 * Feature flag service: EarlyPaymentFeature::isEnabled
 *   (app/Modules/Subscriptions/Services/EarlyPaymentFeature.php:11-16)
 *
 * Tests run with FLUENTCART_PRO_PLUGIN_VERSION defined (functional bootstrap), so
 * App::isProActive() returns true and the feature is enabled by default. Item 26 toggles
 * it off via the `fluent_cart/subscription/early_payment_enabled` filter.
 */
class GenerateEarlyPaymentLinkCest
{
    use BuildsSubscriptions;

    public function _before(FunctionalTester $I): void
    {
        $I->resetFluentCartTables();
    }

    /**
     * Spec: Cases/Functional/subscriptions.md [25]
     *   "Admin can generate an early-installment payment link for an active subscription
     *    that still has remaining installments."
     */
    public function adminCanGenerateEarlyInstallmentPaymentLinkForActiveSubscription(FunctionalTester $I): void
    {

        $I->loginAsSuperAdmin();
        [, , $order, $subscription] = $this->buildSubscriptionChain([
            'item_name'  => 'EarlyPay Probe 25',
            'status'     => Status::SUBSCRIPTION_ACTIVE,
            'bill_times' => 12,
            'bill_count' => 3,
        ]);

        [$status, $body] = $I->post(
            '/fluent-cart/v2/orders/' . (int) $order->id . '/subscriptions/' . (int) $subscription->id . '/early-payment-link',
            []
        );

        Assert::assertSame(200, $status, 'eligible installment subscription must receive a 200 with payment_url. Body: ' . wp_json_encode($body));
        Assert::assertArrayHasKey('payment_url', (array) $body, 'success body must include payment_url generated by SubscriptionController::generateEarlyPaymentLink');
        Assert::assertStringContainsString(
            'fluent-cart=early-installment-payment',
            (string) ($body['payment_url'] ?? ''),
            'payment_url must carry the fluent-cart=early-installment-payment query parameter so the frontend knows which flow to bootstrap'
        );
        Assert::assertStringContainsString(
            (string) $subscription->uuid,
            (string) ($body['payment_url'] ?? ''),
            'payment_url must embed subscription_hash equal to the subscription uuid so the resulting checkout binds to the right subscription'
        );
    }

    /**
     * Spec: Cases/Functional/subscriptions.md [26]
     *   "Generating an early-payment link when the early-payment feature is disabled
     *    site-wide is rejected with a clear error."
     */
    public function generatingEarlyPaymentLinkWhenFeatureIsDisabledSiteWideIsRejected(FunctionalTester $I): void
    {
        $I->loginAsSuperAdmin();
        [, , $order, $subscription] = $this->buildSubscriptionChain([
            'item_name'  => 'EarlyPay Probe 26',
            'status'     => Status::SUBSCRIPTION_ACTIVE,
            'bill_times' => 12,
            'bill_count' => 3,
        ]);

        $disable = static function () {
            return false;
        };
        add_filter('fluent_cart/subscription/early_payment_enabled', $disable, 10, 1);

        try {
            [$status, $body] = $I->post(
                '/fluent-cart/v2/orders/' . (int) $order->id . '/subscriptions/' . (int) $subscription->id . '/early-payment-link',
                []
            );

            Assert::assertSame(
                422,
                $status,
                'feature-disabled rejection must surface the controller sendError 422 (default code from SubscriptionController::generateEarlyPaymentLink line 159-163). Body: ' . wp_json_encode($body)
            );
            Assert::assertStringContainsString(
                'Early payment is not enabled',
                (string) ($body['message'] ?? ''),
                'feature-disabled rejection message must name the site-wide-disabled cause per app/Modules/Subscriptions/Http/Controllers/SubscriptionController.php:161'
            );
            Assert::assertArrayNotHasKey(
                'payment_url',
                (array) $body,
                'feature-disabled rejection must NOT leak a payment_url'
            );
        } finally {
            remove_filter('fluent_cart/subscription/early_payment_enabled', $disable, 10);
        }
    }

    /**
     * Spec: Cases/Functional/subscriptions.md [27]
     *   "Generating an early-payment link for a subscription that does not belong to the
     *    supplied order is rejected with a clear error."
     */
    public function generatingEarlyPaymentLinkForSubscriptionNotBelongingToOrderIsRejected(FunctionalTester $I): void
    {

        $I->loginAsSuperAdmin();

        // Two distinct orders. The subscription belongs to $orderA, but the URL points at
        // $orderB — the controller's "parent_order_id matches URL order" guard at line 170
        // should be what rejects this, not the upstream property_exists bug.
        [, , $orderA, $subscription] = $this->buildSubscriptionChain([
            'item_name'  => 'EarlyPay Probe 27',
            'status'     => Status::SUBSCRIPTION_ACTIVE,
            'bill_times' => 12,
            'bill_count' => 3,
        ]);

        $otherCustomer = (new CustomerFactory())->create(['email' => 'early-pay-27-other@example.test']);
        $orderB        = (new OrderFactory())->create(['customer_id' => $otherCustomer->id]);

        [$status, $body] = $I->post(
            '/fluent-cart/v2/orders/' . (int) $orderB->id . '/subscriptions/' . (int) $subscription->id . '/early-payment-link',
            []
        );

        Assert::assertSame(422, $status, 'subscription/order mismatch must surface the controller sendError 422. Body: ' . wp_json_encode($body));
        Assert::assertStringContainsString(
            'Invalid subscription for the specified order',
            (string) ($body['message'] ?? ''),
            'subscription/order mismatch rejection message must name the cause per app/Modules/Subscriptions/Http/Controllers/SubscriptionController.php:172'
        );
        Assert::assertArrayNotHasKey('payment_url', (array) $body, 'mismatch rejection must NOT leak a payment_url');
    }

